package nl.kmartin.dartsmatcher.api.features.x01.x01dartbot.service;

import nl.kmartin.dartsmatcher.api.features.x01.x01dartbot.util.PiecewiseLinearInterpolator;
import org.springframework.stereotype.Service;
import org.springframework.validation.annotation.Validated;

import java.util.Map;
import java.util.NavigableMap;
import java.util.TreeMap;
import java.util.concurrent.ThreadLocalRandom;

/**
 * Calculates Gaussian throw offsets using a measured baseline standard deviation
 * and performance calibration.
 *
 * Standard deviation controls how closely throws group around the target on each axis,
 * in millimeters. It is not a distance limit: larger offsets are possible but less likely.
 * Calibration adjusts this value based on the bot's current performance.
 */
@Service
@Validated
public class X01DartBotDeviationCalculatorImpl implements IX01DartBotDeviationCalculator {

    // Calibration strength when the bot's current average is above target.
    private static final double OVERPERFORMANCE_CALIBRATION_FACTOR = 2.5;

    // Stronger calibration when below target to help the bot catch up.
    private static final double UNDERPERFORMANCE_CALIBRATION_FACTOR = 5.0;

    /**
     * Maps three-dart averages rounded upward to baseline standard deviations in millimeters.
     * Generated by {@code X01DartBotStdDevCurveGenerator.generateStandardDeviationCurve()}.
     */
    private static final NavigableMap<Double, Double> STANDARD_DEVIATION_CURVE = new TreeMap<>(Map.ofEntries(
            Map.entry(3.00, 200.0),
            Map.entry(4.00, 150.0),
            Map.entry(6.00, 125.0),
            Map.entry(8.00, 100.0),
            Map.entry(11.00, 80.0),
            Map.entry(14.00, 70.0),
            Map.entry(16.00, 60.0),
            Map.entry(20.00, 50.0),
            Map.entry(25.00, 40.0),
            Map.entry(28.00, 35.0),
            Map.entry(32.00, 30.0),
            Map.entry(38.00, 25.0),
            Map.entry(46.00, 20.0),
            Map.entry(50.00, 18.0),
            Map.entry(57.00, 16.0),
            Map.entry(64.00, 14.0),
            Map.entry(73.00, 12.0),
            Map.entry(84.00, 10.0),
            Map.entry(91.00, 9.0),
            Map.entry(98.00, 8.0),
            Map.entry(106.00, 7.0),
            Map.entry(115.00, 6.0),
            Map.entry(125.00, 5.0),
            Map.entry(138.00, 4.0),
            Map.entry(145.00, 3.5),
            Map.entry(153.00, 3.0),
            Map.entry(165.00, 2.0),
            Map.entry(167.00, 0.0)
    ));

    private final PiecewiseLinearInterpolator standardDeviationInterpolator =
            new PiecewiseLinearInterpolator(STANDARD_DEVIATION_CURVE);

    @Override
    public double createOffset(double standardDeviation) {
        if (!Double.isFinite(standardDeviation) || standardDeviation < 0) {
            throw new IllegalArgumentException("Standard deviation must be finite and non-negative");
        }

        if (standardDeviation == 0) {
            return 0;
        }

        return ThreadLocalRandom.current().nextGaussian() * standardDeviation;
    }

    @Override
    public double getStandardDeviation(double targetOneDartAvg) {
        return standardDeviationInterpolator.interpolateY(targetOneDartAvg * 3.0);
    }

    @Override
    public double getCalibratedStandardDeviation(double targetOneDartAvg, double currentOneDartAvg) {
        double baselineStandardDeviation = getStandardDeviation(targetOneDartAvg);
        double calibrationMultiplier = getCalibrationMultiplier(targetOneDartAvg, currentOneDartAvg);
        double adjustedStandardDeviation = baselineStandardDeviation * calibrationMultiplier;

        return Math.max(
                getMinimumStandardDeviation(),
                Math.min(getMaximumStandardDeviation(), adjustedStandardDeviation)
        );
    }


    /**
     * Calculates the standard deviation multiplier from the relative difference
     * between the current and target averages, applying stronger correction when behind.
     *
     * @param targetOneDartAvg  the positive target one-dart average
     * @param currentOneDartAvg the current one-dart average
     * @return the calibration multiplier, which can be negative before clamping
     */
    private double getCalibrationMultiplier(double targetOneDartAvg, double currentOneDartAvg) {
        double relativePerformanceDifference = (currentOneDartAvg - targetOneDartAvg) / targetOneDartAvg;

        double calibrationFactor = relativePerformanceDifference > 0
                ? OVERPERFORMANCE_CALIBRATION_FACTOR
                : UNDERPERFORMANCE_CALIBRATION_FACTOR;

        return 1.0 + calibrationFactor * relativePerformanceDifference;
    }

    /**
     * Gets the minimum standard deviation at the curve's highest average.
     *
     * @return the minimum standard deviation per axis in millimeters
     */
    private double getMinimumStandardDeviation() {
        return STANDARD_DEVIATION_CURVE.lastEntry().getValue();
    }

    /**
     * Gets the maximum standard deviation at the curve's lowest average.
     *
     * @return the maximum standard deviation per axis in millimeters
     */
    private double getMaximumStandardDeviation() {
        return STANDARD_DEVIATION_CURVE.firstEntry().getValue();
    }
}